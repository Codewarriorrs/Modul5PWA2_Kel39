-- 1. BERSIHKAN TABEL LAMA JIKA ADA (DROP TABLES)
drop table if exists public.favorites cascade;
drop table if exists public.reviews cascade;
drop table if exists public.products cascade;

-- 2. TABEL PRODUCTS (SENJATA / HARDWARE)
create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null default 'Pistol',
  caliber text,
  price numeric(10, 2) not null default 0,
  description text,
  specs text[] default array[]::text[],
  steps text[] default array[
    'Verify firearm is completely unloaded and point in safe direction.',
    'Inspect receiver and mechanism for maintenance.'
  ]::text[],
  image_url text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 3. TABEL REVIEWS (ULASAN & RATING PRODUK)
create table public.reviews (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete cascade not null,
  user_id text not null,
  rating integer not null check (rating >= 1 and rating <= 5),
  comment text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 4. TABEL FAVORITES (DAFTAR FAVORIT PENGGUNA)
create table public.favorites (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete cascade not null,
  user_id text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  constraint unique_user_product unique (user_id, product_id)
);

-- 5. STORAGE BUCKET UNTUK UPLOAD GAMBAR
insert into storage.buckets (id, name, public)
values ('guns', 'guns', true)
on conflict (id) do update set public = true;

-- 6. SETUP ROW LEVEL SECURITY (RLS) & PUBLIC POLICIES
-- Aktifkan RLS
alter table public.products enable row level security;
alter table public.reviews enable row level security;
alter table public.favorites enable row level security;

-- Kebijakan Akses Penuh (CRUD Publik untuk Praktikum)
create policy "Allow public all on products" on public.products
  for all using (true) with check (true);

create policy "Allow public all on reviews" on public.reviews
  for all using (true) with check (true);

create policy "Allow public all on favorites" on public.favorites
  for all using (true) with check (true);

-- Kebijakan Akses Storage Bucket 'guns'
create policy "Allow public uploads to guns bucket" on storage.objects
  for insert with check (bucket_id = 'guns');

create policy "Allow public read from guns bucket" on storage.objects
  for select using (bucket_id = 'guns');

create policy "Allow public update/delete guns bucket" on storage.objects
  for update using (bucket_id = 'guns');

create policy "Allow public delete guns bucket" on storage.objects
  for delete using (bucket_id = 'guns');

